#!/usr/bin/env python3
"""
Generates the images of the Advanced Color Picker plugin:
source/plugins/advancedcolorpicker/src/picker_images.lua

    python3 source/tools/gen_picker_images.py           # write the file
    python3 source/tools/gen_picker_images.py --check   # fail if it is out of date

The colours are drawn as images because UCI styles (CSS) override the colours of
buttons, but not images. The plugin puts invisible buttons on top for touch.
Uses only the standard library (zlib), no Pillow needed.

(c) levo AVL | Elias Jenny - MIT License
"""

import argparse
import base64
import colorsys
import math
import re
import struct
import sys
import zlib
from pathlib import Path

SOURCE = Path(__file__).resolve().parent.parent
PLUGIN = SOURCE / "plugins" / "advancedcolorpicker" / "src"
OUT = PLUGIN / "picker_images.lua"

WHEEL_PX = 256   # scaled to the layout size by Q-SYS
WHEEL_SAT = 0.95  # full saturation is reached at this fraction of the radius (outer ring)


def filtered(rows, bpp):
    """PNG row filters: per row the one with the smallest sum (standard heuristic).
    Gradients compress several times better than unfiltered."""
    prev = bytes(len(rows[0]))
    for row in rows:
        cands = []
        for ftype in range(5):
            out = bytearray(len(row))
            for i, x in enumerate(row):
                a = row[i - bpp] if i >= bpp else 0
                b = prev[i]
                c = prev[i - bpp] if i >= bpp else 0
                if ftype == 0: pred = 0
                elif ftype == 1: pred = a
                elif ftype == 2: pred = b
                elif ftype == 3: pred = (a + b) // 2
                else:
                    pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                    pred = a if pa <= pb and pa <= pc else (b if pb <= pc else c)
                out[i] = (x - pred) & 0xFF
            score = sum(v if v < 128 else 256 - v for v in out)
            cands.append((score, ftype, bytes(out)))
        _, ftype, out = min(cands)
        yield bytes([ftype]) + out
        prev = row


def png(width, height, rows, alpha):
    """rows: list of bytes, one per row, RGB or RGBA."""
    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
    raw = b"".join(filtered(rows, 4 if alpha else 3))
    ihdr = struct.pack(">IIBBBBB", width, height, 8, 6 if alpha else 2, 0, 0, 0)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr)
            + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def wheel():
    """Hue = angle (red on top, clockwise), saturation = distance, full brightness.
    Same mapping as WheelCell() in presets.lua. Anti-aliased, transparent outside."""
    n = WHEEL_PX
    c = (n - 1) / 2
    radius = n / 2
    rows = []
    for y in range(n):
        row = bytearray()
        for x in range(n):
            dx, dy = x - c, y - c
            dist = math.hypot(dx, dy)
            a = max(0.0, min(1.0, radius - dist))  # 1 px soft edge
            hue = (math.degrees(math.atan2(dx, -dy)) % 360) / 360
            sat = min(1.0, dist / (radius * WHEEL_SAT))
            r, g, b = colorsys.hsv_to_rgb(hue, sat, 1.0)
            row += bytes((round(r * 255), round(g * 255), round(b * 255), round(a * 255)))
        rows.append(bytes(row))
    return png(n, n, rows, True)


def swatch(hexcode):
    """Solid 4x4 colour, scaled up by Q-SYS."""
    rgb = bytes(int(hexcode[i:i + 2], 16) for i in (1, 3, 5))
    return png(4, 4, [rgb * 4] * 4, False)


def preset_hexes():
    text = (PLUGIN / "presets.lua").read_text(encoding="utf-8")
    return re.findall(r'Hex = "(#[0-9A-Fa-f]{6})"', text)


def generate():
    b64 = lambda data: base64.b64encode(data).decode("ascii")
    lines = [
        "-- AUTO-GENERATED by source/tools/gen_picker_images.py - do not edit by hand.",
        "-- (c) levo AVL | Elias Jenny - MIT License",
        "",
        "PickerImages = {",
        f'  Wheel = "{b64(wheel())}",',
        "  Swatch = {",
    ]
    for hexcode in preset_hexes():
        lines.append(f'    ["{hexcode.upper()}"] = "{b64(swatch(hexcode.upper()))}",')
    lines += ["  },", "}", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="only check that the file is up to date")
    args = ap.parse_args()
    text = generate()
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            sys.exit(f"{OUT.relative_to(SOURCE.parent)} is out of date - run {Path(__file__).name}")
        print("  picker images up to date")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"  wrote {OUT.relative_to(SOURCE.parent)} ({len(text) // 1024} KB)")


if __name__ == "__main__":
    main()
