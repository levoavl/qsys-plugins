#!/usr/bin/env python3
"""
Build tool for levo AVL Q-SYS plugins.

Usage (from the repository root):
    python3 source/tools/build.py              # build all plugins
    python3 source/tools/build.py grandma2     # build one plugin
    python3 source/tools/build.py --check      # build + Lua 5.3 syntax check (needs `pip install lupa`)
    python3 source/tools/build.py sound2beat --dev   # test build with dev stamp, see below

What it does:
    1. Regenerates source/shared/lua/levo_assets.lua from the logo originals in
       source/shared/assets (not published; skipped when they are missing).
    2. For every plugin in source/plugins/<name>/src/plugin.lua, resolves
       --[[ #include "file.lua" ]] directives recursively and writes levo-<name>.qplug:
       - into the plugin's public folder in the repository root (e.g. grandMA2/),
         matched case-insensitively against <name>, once the plugin is released;
       - otherwise next to its sources in source/plugins/<name>/.

--dev builds a test copy into source/.dev-build/ (not committed) instead of the normal
output. The test copy is stamped with branch, commit and build time, shown in the schematic
block under the plugin name and on the About page, e.g. "dev sound2beat a1b2c3d+ 22.10. 12:41"
("+" = uncommitted changes). File name and plugin Id stay the same, so the test copy simply
replaces the previous one in the Q-SYS plugin folder. The version gets the build time as
a third part (1.0 -> 1.0.2610281135) so Designer offers the update in existing designs.
Released files never carry a stamp.

Include lookup order: the plugin's own src/ folder first, then source/shared/lua/.
The include syntax is the same one the QSC plugin compiler uses, so the sources
stay compatible with that workflow as well.
"""

import argparse
import base64
import io
import re
import sys
from pathlib import Path

SOURCE = Path(__file__).resolve().parent.parent
ROOT = SOURCE.parent
PLUGINS = SOURCE / "plugins"
SHARED_LUA = SOURCE / "shared" / "lua"
ASSETS = SOURCE / "shared" / "assets"

INCLUDE_RE = re.compile(r'--\[\[\s*#include\s+"([^"]+)"\s*\]\]')

# Logos embedded in the plugins (file stem -> pixel width). Only what the layouts
# actually use, rendered at a fraction of this size so it stays sharp on touch panels.
EMBED_WIDTHS = {
    "wordmark-porcelain": 360,  # header bar
    "wordmark-atlantic": 360,   # About page
}


def generate_assets() -> None:
    """Write shared/lua/levo_assets.lua with base64-encoded logo PNGs."""
    # The logo originals are not published (see shared/NOTICE.md). Without them
    # the committed levo_assets.lua is used as is.
    if not any(ASSETS.glob("*.png")):
        print("  assets  (no logo originals - using committed levo_assets.lua)")
        return
    try:
        from PIL import Image
    except ImportError:
        print("  ! Pillow not installed - keeping existing levo_assets.lua")
        return

    lines = [
        "-- AUTO-GENERATED by tools/build.py from shared/assets - do not edit by hand.",
        "-- (c) levo AVL | Elias Jenny - MIT License",
        "",
        "LevoAssets = {",
    ]
    for png in sorted(ASSETS.glob("*.png")):
        width = EMBED_WIDTHS.get(png.stem)
        if width is None:
            continue
        im = Image.open(png).convert("RGBA")
        height = round(im.height * width / im.width)
        im = im.resize((width, height), Image.LANCZOS)
        buf = io.BytesIO()
        im.save(buf, format="PNG", optimize=True)
        b64 = base64.b64encode(buf.getvalue()).decode("ascii")
        key = png.stem.replace("-", "_")
        lines.append(f'  {key} = {{ Width = {width}, Height = {height},')
        lines.append(f'    Data = "{b64}" }},')
    lines.append("}")
    SHARED_LUA.mkdir(parents=True, exist_ok=True)
    (SHARED_LUA / "levo_assets.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("  assets  -> source/shared/lua/levo_assets.lua")


def resolve(path: Path, search: list, stack: list) -> str:
    if path in stack:
        chain = " -> ".join(p.name for p in stack + [path])
        raise SystemExit(f"Include cycle: {chain}")
    text = path.read_text(encoding="utf-8")

    def replace(match):
        name = match.group(1)
        for folder in search:
            candidate = folder / name
            if candidate.is_file():
                body = resolve(candidate, search, stack + [path])
                return f"-- >>> {name}\n{body.rstrip()}\n-- <<< {name}"
        raise SystemExit(f'{path.relative_to(ROOT)}: include "{name}" not found')

    return INCLUDE_RE.sub(replace, text)


def lua_check(source: str, name: str) -> None:
    try:
        from lupa.lua53 import LuaRuntime  # Q-SYS runs Lua 5.3
    except ImportError:
        print("  ! lupa not installed - skipping syntax check (pip install lupa)")
        return
    lua = LuaRuntime()
    err = lua.eval("function(src, name) local _, e = load(src, '=' .. name) return e end")(source, name)
    if err:
        raise SystemExit(f"Lua syntax error: {err}")


DEV_DIR = SOURCE / ".dev-build"


def dev_stamp() -> str:
    import subprocess
    from datetime import datetime
    try:
        from zoneinfo import ZoneInfo
        now = datetime.now(ZoneInfo("Europe/Berlin"))
    except Exception:
        now = datetime.now()

    def git(*args):
        r = subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, text=True)
        return r.stdout.strip() if r.returncode == 0 else ""

    branch = git("rev-parse", "--abbrev-ref", "HEAD") or "?"
    commit = git("rev-parse", "--short=7", "HEAD") or "?"
    dirty = "+" if git("status", "--porcelain", "--", "source") else ""
    return f"dev {branch} {commit}{dirty} {now:%d.%m. %H:%M}", now.strftime("%y%m%d%H%M")


def stamp_source(source: str, stamp: str, build_no: str) -> str:
    """Append Lua that shows the dev stamp without touching the plugin's own code.
    The version gets the build time as a third part (1.0 -> 1.0.2610281135): Designer
    only offers to update a plugin in a design when the version in the plugin folder is
    newer, so every test build must count up."""
    return source.rstrip() + f"""

-- >>> dev build stamp (added by build.py --dev, never in released files)
PluginInfo.DevBuild = "{stamp}"
PluginInfo.Version = PluginInfo.Version .. ".{build_no}"
PluginInfo.BuildVersion = PluginInfo.BuildVersion .. ".{build_no}"
do
  local prettyName = GetPrettyName
  GetPrettyName = function(props) return prettyName(props) .. "\\n" .. PluginInfo.DevBuild end
  if LevoBrand and LevoBrand.About then
    local about = LevoBrand.About
    LevoBrand.About = function(graphics, x, y, width, info)
      local bottom = about(graphics, x, y, width, info)
      table.insert(graphics, {{ Type = "Text", Text = "Test build: " .. PluginInfo.DevBuild,
        Position = {{ x, bottom + 4 }}, Size = {{ width, 18 }}, FontSize = 11, FontStyle = "Bold",
        HTextAlign = "Left", Color = LevoBrand.Colors.Atlantic }})
      return bottom + 22
    end
  end
end
-- <<< dev build stamp
"""


def output_path(name: str) -> Path:
    """Where the built .qplug of plugin <name> goes (see module docstring)."""
    for folder in ROOT.iterdir():
        if folder.is_dir() and folder.name.lower() == name.lower() and folder != SOURCE:
            return folder / f"levo-{name}.qplug"
    return PLUGINS / name / f"levo-{name}.qplug"


def build(plugin_dir: Path, check: bool, dev: bool = False) -> None:
    entry = plugin_dir / "src" / "plugin.lua"
    if not entry.is_file():
        print(f"  skip    {plugin_dir.name} (no src/plugin.lua yet)")
        return
    source = resolve(entry, [plugin_dir / "src", SHARED_LUA], [])
    out = output_path(plugin_dir.name)
    if dev:
        stamp, build_no = dev_stamp()
        source = stamp_source(source, stamp, build_no)
        DEV_DIR.mkdir(exist_ok=True)
        out = DEV_DIR / out.name
    if check:
        lua_check(source, out.name)
    out.write_text(source, encoding="utf-8", newline="\r\n")
    print(f"  built   {out.relative_to(ROOT)} ({len(source) // 1024} KB)")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("plugins", nargs="*", help="plugin folder names (default: all)")
    parser.add_argument("--check", action="store_true", help="Lua 5.3 syntax check of the result")
    parser.add_argument("--dev", action="store_true",
                        help="stamped test build into source/.dev-build/ (not committed)")
    args = parser.parse_args()

    generate_assets()
    names = args.plugins or sorted(p.name for p in PLUGINS.iterdir() if p.is_dir())
    for name in names:
        folder = PLUGINS / name
        if not folder.is_dir():
            sys.exit(f"Unknown plugin: {name}")
        build(folder, args.check or args.dev, args.dev)


if __name__ == "__main__":
    main()
