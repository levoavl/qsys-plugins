#!/usr/bin/env python3
"""
Generate source/plugins/atem/src/atem_models.lua - the ATEM model table of the
ATEM plugin (counts and source lists per switcher model).

The data comes from the model specs of the Bitfocus Companion module for ATEM
switchers (https://github.com/bitfocus/companion-module-bmd-atem, MIT License,
Copyright (c) 2018 Bitfocus AS, William Viker & Hakon Nessjoen). Those specs are
TypeScript, so this tool runs them once with Node.js and converts the result.

Usage (from the repository root, needs Node.js 22+ and npm):
    git clone --depth 1 https://github.com/bitfocus/companion-module-bmd-atem /tmp/bmd-atem
    python3 source/tools/gen_atem_models.py /tmp/bmd-atem

(c) levo AVL | Elias Jenny - MIT License
"""

import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "source" / "plugins" / "atem" / "src" / "atem_models.lua"

DUMP_TS = r"""
import { ALL_MODELS } from './models/index.js'
import { Enums } from 'atem-connection'
const out = ALL_MODELS.filter((m) => m.id !== 0).map((m) => ({
  id: m.id, label: m.label,
  MEs: m.MEs, USKs: m.USKs, DSKs: m.DSKs, SSrc: m.SSrc, macros: m.macros,
  media: m.media, streaming: m.streaming, recording: m.recording, recordISO: m.recordISO,
  outputs: m.outputs,
  inputs: m.inputs.map((i) => [i.id, i.portType, i.sourceAvailability, i.meAvailability]),
  classic: m.classicAudio ? m.classicAudio.inputs.map((i) => [i.id, i.portType]) : null,
  fairlight: m.fairlightAudio ? m.fairlightAudio.inputs.map((i) => [i.id, i.portType]) : null,
}))
console.log(JSON.stringify(out))
"""


def dump(module_dir: Path) -> list:
    pkg = json.loads((module_dir / "package.json").read_text())
    atem_version = pkg["dependencies"]["atem-connection"].lstrip("^~")
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        shutil.copytree(module_dir / "src" / "models", tmp / "models",
                        ignore=shutil.ignore_patterns("__tests__"))
        # the model index only needs `compact` from the module's util.ts
        (tmp / "util.ts").write_text(
            "export function compact<T>(a: Array<T | undefined | null | false>): T[] "
            "{ return a.filter((x) => !!x) as T[] }\n")
        index = tmp / "models" / "index.ts"
        index.write_text(index.read_text().replace("'../util.js'", "'../util.ts'"))
        (tmp / "package.json").write_text('{"type":"module"}')
        (tmp / "dump.ts").write_text(DUMP_TS)
        subprocess.run(["npm", "install", "--silent", f"atem-connection@{atem_version}",
                        "tsx", "@companion-module/base", "lodash-es"], cwd=tmp, check=True)
        res = subprocess.run(["npx", "tsx", "dump.ts"], cwd=tmp, check=True,
                             capture_output=True, text=True)
        return json.loads(res.stdout), atem_version, pkg.get("version", "?")


def lua_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def flat(rows) -> str:
    return "{" + ",".join(str(v) for row in rows for v in row) + "}"


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    models, atem_version, module_version = dump(Path(sys.argv[1]))
    lines = [
        "-- AUTO-GENERATED by source/tools/gen_atem_models.py - do not edit by hand.",
        f"-- Source: Bitfocus Companion module bmd-atem {module_version} (atem-connection {atem_version}),",
        "-- MIT License, Copyright (c) 2018 Bitfocus AS, William Viker & Hakon Nessjoen.",
        "-- (c) levo AVL | Elias Jenny - MIT License",
        "--",
        "-- Sources: flat list, 4 numbers per source: id, internal port type,",
        "--   source availability (bit mask), M/E availability (bit mask).",
        "-- Audio inputs: flat list, 2 numbers per input: id, external port type.",
        "",
        "AtemModels = {",
    ]
    for m in models:
        label = m["label"]
        name = "ATEM " + re.sub(r"\bME\b", "M/E", label)
        aux = sum(1 for o in m["outputs"])
        audio = "Fairlight" if m["fairlight"] else ("Classic" if m["classic"] else "None")
        audio_inputs = m["fairlight"] or m["classic"] or []
        lines += [
            "  {",
            f"    Id = {m['id']}, Name = {lua_str(name)},",
            f"    MEs = {m['MEs']}, USKs = {m['USKs']}, DSKs = {m['DSKs']}, SuperSources = {m['SSrc']},",
            f"    Aux = {aux}, MediaPlayers = {m['media']['players']}, Stills = {m['media']['stills']},"
            f" Clips = {m['media']['clips']}, Macros = {m['macros']},",
            f"    Streaming = {str(m['streaming']).lower()}, Recording = {str(m['recording']).lower()},"
            f" RecordISO = {str(m['recordISO']).lower()},",
            f"    Audio = {lua_str(audio)}, AudioInputs = {flat(audio_inputs)},",
            f"    Sources = {flat(m['inputs'])},",
            "  },",
        ]
    lines.append("}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  wrote {OUT.relative_to(ROOT)} ({len(models)} models)")


if __name__ == "__main__":
    main()
