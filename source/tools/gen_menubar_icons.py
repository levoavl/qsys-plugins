#!/usr/bin/env python3
"""Generate source/plugins/menubar/src/icons.lua from Google Material Symbols.

Usage: npm pack @material-symbols/svg-400, extract it, then
  python3 source/tools/gen_menubar_icons.py <path-to-extracted>/package
Material Symbols (c) Google, Apache License 2.0.
"""
import re, sys
from pathlib import Path

ICONS = """power_settings_new power mic mic_off desktop_windows monitor tv connected_tv live_tv
videocam video_camera_front lightbulb light_mode dark_mode emoji_objects settings tune home
volume_up volume_down volume_off speaker headphones graphic_eq equalizer music_note radio movie
theaters slideshow present_to_all screen_share cast input settings_input_hdmi play_arrow pause stop
info help warning lock lock_open menu apps dashboard grid_view thermostat wifi lan router blinds
curtains roller_shades meeting_room groups person event schedule call photo_camera tablet_mac
admin_panel_settings build celebration restaurant local_bar campaign palette bolt arrow_back
arrow_forward close add remove check_circle language web
settings_input_component settings_input_svideo instant_mix input_circle media_output cable bluetooth
airplay queue_music library_music album playlist_play podcasts speaker_group""".split()

def paths(svg: str) -> str:
    return "".join(re.findall(r'<path d="([^"]+)"', svg))

def main() -> None:
    pkg = Path(sys.argv[1]) / "rounded"
    out = Path(__file__).resolve().parents[1] / "plugins" / "menubar" / "src" / "icons.lua"
    lines = [
        "-- Generated by source/tools/gen_menubar_icons.py - do not edit by hand.",
        "-- Material Symbols (Rounded, weight 400) (c) Google LLC, Apache License 2.0.",
        "-- Path data in viewBox 0 -960 960 960. o = outline, f = filled.",
        "MenuIcons = {",
    ]
    for name in ICONS:
        o = paths((pkg / f"{name}.svg").read_text())
        fp = pkg / f"{name}-fill.svg"
        f = paths(fp.read_text()) if fp.exists() else o
        lines.append(f'  ["{name}"] = {{ o = "{o}", f = "{f}" }},')
    lines.append("}")
    lines.append("MenuIconNames = {}")
    lines.append("for k in pairs(MenuIcons) do table.insert(MenuIconNames, k) end")
    lines.append("table.sort(MenuIconNames)")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({out.stat().st_size // 1024} KB, {len(ICONS)} icons)")

if __name__ == "__main__":
    main()
